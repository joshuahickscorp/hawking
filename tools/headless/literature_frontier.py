def _t(
    *,
    name: str,
    arxiv_id: str,
    arxiv_date: str,
    authors: str,
    family: str,
    families: tuple[str, ...],
    mechanism: str,
    hawking_organ: str,
    hawking_gap: str,
    codebase_citations: tuple[str, ...],
    metal_feasibility: str,
    metal_note: str,
    expected_physical_win_axis: str,
    expected_physical_win: str,
    cheapest_falsifying_experiment: str,
    n043_seed: bool,
    info_gain: int,
    physical_upside: int,
    experiment_cost: int,
    add_reason_yes: str,
    add_reason_no: str,
    license: str | None = None,
    code_url: str | None = None,
    venue: str | None = None,
    negative_science: str | None = None,
    more_recent_than_n043: bool = False,
    force_add: bool | None = None,
) -> dict[str, Any]:
    if family not in SURVEY_FAMILIES:
        raise ValueError(f"unknown family {family!r} for {name}")
    for f in families:
        if f not in SURVEY_FAMILIES:
            raise ValueError(f"unknown family {f!r} for {name}")
    if expected_physical_win_axis not in COST_AXES:
        raise ValueError(f"unknown axis {expected_physical_win_axis!r} for {name}")
    if hawking_organ not in ORGAN_LIBRARY_IDS and hawking_organ not in (
        "mlp",
        "embedding_output",
        "session_state",
        "decode_loop",
        "whole_model",
    ):
        raise ValueError(f"unknown organ {hawking_organ!r} for {name}")
    if not (1 <= info_gain <= 5 and 1 <= physical_upside <= 5 and 1 <= experiment_cost <= 5):
        raise ValueError(f"scores out of range for {name}")
    return {
        "name": name,
        "arxiv_id": arxiv_id,
        "arxiv_date": arxiv_date,
        "authors": authors,
        "venue": venue,
        "license": license,
        "code_url": code_url,
        "family": family,
        "families": list(families),
        "mechanism": mechanism,
        "hawking_organ": hawking_organ,
        "hawking_gap": hawking_gap,
        "codebase_citations": list(codebase_citations),
        "metal_feasibility": metal_feasibility,
        "metal_note": metal_note,
        "expected_physical_win_axis": expected_physical_win_axis,
        "expected_physical_win": expected_physical_win,
        "cheapest_falsifying_experiment": cheapest_falsifying_experiment,
        "n043_seed": n043_seed,
        "more_recent_than_n043": more_recent_than_n043,
        "negative_science": negative_science,
        "info_gain": info_gain,
        "physical_upside": physical_upside,
        "experiment_cost": experiment_cost,
        "add_reason_yes": add_reason_yes,
        "add_reason_no": add_reason_no,
        "force_add": force_add,
        "literature_status": "HYPOTHESIS",
        "not_a_verdict": True,
    }


