def _n043_names(registry: dict[str, Any] | None) -> set[str]:
    names = {n.lower() for n in N043_SEED}
    if not registry:
        return names
    for key in ("techniques", "entries", "registry", "hypotheses"):
        items = registry.get(key)
        if isinstance(items, list):
            for it in items:
                if isinstance(it, dict):
                    for nk in ("name", "technique", "id", "short_name"):
                        v = it.get(nk)
                        if isinstance(v, str) and v.strip():
                            names.add(v.strip().lower())
    return names


def _rank_score(row: dict[str, Any]) -> float:
    return (row["info_gain"] * row["physical_upside"]) / row["experiment_cost"]


def _decide_add(row: dict[str, Any], n043: set[str]) -> tuple[str, str]:
    """ADD_TO_REGISTRY yes/no with reason. Literature remains a hypothesis.

    Worth-adding bar (S026 §114): skip N043 seeds, skip closed negatives
    (force_add False), skip experiment_cost=5 architecture/QAT rebuilds,
    skip rank_score < 3. Cheap probes and high-EV 2025-26 successors stay.
    """
    score = _rank_score(row)
    if row["force_add"] is False:
        return "no", row["add_reason_no"]
    if row["n043_seed"]:
        return "no", row["add_reason_no"]
    if row["name"].lower() in n043:
        return "no", "Already present in N043 registry/seed."
    if row["experiment_cost"] >= 5:
        return (
            "no",
            row["add_reason_no"]
            or (
                "Catalogued, not added: experiment_cost=5 (QAT or architecture "
                "rebuild). Current-Qwen GPU is N042; cheap probes first (S026 §85, §114)."
            ),
        )
    if score < 3:
        return (
            "no",
            row["add_reason_no"]
            or (
                f"Catalogued, not added: rank_score={score:.2f} < 3. "
                "Does not beat cheaper probes on this parent/machine."
            ),
        )
    return "yes", row["add_reason_yes"] or "New vs N043 seed; EV clears the add bar."


